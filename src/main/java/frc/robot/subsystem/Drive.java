package frc.robot.subsystem;

import org.littletonrobotics.junction.Logger;

import edu.wpi.first.math.geometry.Pose2d;
import edu.wpi.first.math.geometry.Rotation2d;
import edu.wpi.first.math.kinematics.DifferentialDriveOdometry;
import edu.wpi.first.wpilibj.drive.DifferentialDrive;
import edu.wpi.first.wpilibj2.command.SubsystemBase;
import frc.robot.Constants;

/**
 * The drivetrain: two motors on each side, like a tank. To turn, one side
 * spins faster than the other.
 *
 * A subsystem is one physical part of the robot. Commands ask it to do things,
 * and only one command can control it at a time.
 *
 * This class decides WHAT the motors should do. The DriveIO it's given (real
 * or simulated) does the actual talking to the motors.
 */
public class Drive extends SubsystemBase {
  private final DriveIO io;
  // DriveIOInputsAutoLogged is generated by AdvantageKit from DriveIO.DriveIOInputs
  private final DriveIOInputsAutoLogged inputs = new DriveIOInputsAutoLogged();
  private final GyroIO gyroIO;
  private final GyroIOInputsAutoLogged gyroInputs = new GyroIOInputsAutoLogged();

  private final DifferentialDrive robotDrive;

  // Odometry keeps track of where the robot is on the field by adding up how far
  // each side's wheels have turned. It's created on the first periodic() so it
  // starts from the encoders' first real readings.
  private DifferentialDriveOdometry odometry = null;

  // Which way the robot is facing, and the wheel distances from the last loop
  // (used to estimate turning from the wheels when there's no gyro)
  private Rotation2d heading = Rotation2d.kZero;
  private double lastLeftMeters = 0.0;
  private double lastRightMeters = 0.0;

  public Drive(DriveIO io, GyroIO gyroIO) {
    this.io = io;
    this.gyroIO = gyroIO;

    // DifferentialDrive constructor takes DoubleConsumer x2,
    // DoubleConsumer is just a function that takes in a double
    // DifferentialDrive turns "speed + turn" into a power for each side,
    // and these two functions scale that power down and send it to the motors.
    robotDrive = new DifferentialDrive(
      (double x) -> {
        double output = x * Constants.DriveConstants.DampenLeft;
        Logger.recordOutput("Drive/LeftOutput", output);
        io.setLeft(output);
      },
      (double x) -> {
        double output = x * Constants.DriveConstants.DampenRight;
        Logger.recordOutput("Drive/RightOutput", output);
        io.setRight(output);
      }
    );
  }

  /** Runs every 20 ms: read the motors' sensors, update the robot's position, and log them. */
  @Override
  public void periodic() {
    io.updateInputs(inputs);
    Logger.processInputs("Drive", inputs);
    gyroIO.updateInputs(gyroInputs);
    Logger.processInputs("Drive/Gyro", gyroInputs);

    updateHeading();

    if (odometry == null) {
      odometry = new DifferentialDriveOdometry(
        heading, getLeftMeters(), getRightMeters(), Constants.DriveConstants.StartingPose
      );
    } else {
      odometry.update(heading, getLeftMeters(), getRightMeters());
    }
    // AdvantageScope draws the robot on the field at this position
    Logger.recordOutput("Odometry/Robot", getPose());
  }

  /** Where the robot is on the field (meters and heading). */
  public Pose2d getPose() {
    if (odometry == null) {
      return Constants.DriveConstants.StartingPose;
    }
    return odometry.getPoseMeters();
  }

  /** Tell odometry the robot is now at "pose", e.g. at the start of autonomous. */
  public void resetPose(Pose2d pose) {
    if (odometry != null) {
      odometry.resetPosition(heading, getLeftMeters(), getRightMeters(), pose);
    }
  }

  /** How far the left wheels have rolled, in meters. */
  private double getLeftMeters() {
    return inputs.leftPositionRotations / Constants.DriveConstants.GearRatio
        * Math.PI * Constants.DriveConstants.WheelDiameterMeters;
  }

  /** How far the right wheels have rolled, in meters. */
  private double getRightMeters() {
    return inputs.rightPositionRotations / Constants.DriveConstants.GearRatio
        * Math.PI * Constants.DriveConstants.WheelDiameterMeters;
  }

  /**
   * Work out which way the robot is facing. If the gyro is connected we use it.
   * If not (in the simulator, or if the gyro is unplugged), we estimate the turn
   * from the wheels: if the right side moved farther than the left since last
   * loop, the robot turned left. Wheels slip, so that estimate drifts over time.
   */
  private void updateHeading() {
    double leftMeters = getLeftMeters();
    double rightMeters = getRightMeters();

    if (gyroInputs.connected) {
      heading = gyroInputs.yawPosition;
    } else if (odometry != null) {
      double turnRadians = ((rightMeters - lastRightMeters) - (leftMeters - lastLeftMeters))
          / Constants.DriveConstants.TrackWidthMeters;
      heading = heading.plus(new Rotation2d(turnRadians));
    }

    lastLeftMeters = leftMeters;
    lastRightMeters = rightMeters;
  }

  /** Set each side's power directly (-1 to 1). Note: skips the Dampen scaling. */
  public void setMotors(double leftSpeed, double rightSpeed) {
    Logger.recordOutput("Drive/LeftOutput", leftSpeed);
    Logger.recordOutput("Drive/RightOutput", rightSpeed);
    io.setLeft(leftSpeed);
    io.setRight(rightSpeed);
  }

  /**
   * @param velocity Forward/backward, -1 to 1
   * @param rotation Turning, -1 to 1
   */
  public void arcadeDrive(double velocity, double rotation) {
    Logger.recordOutput("Drive/RequestedVelocity", velocity);
    Logger.recordOutput("Drive/RequestedRotation", rotation);
    robotDrive.arcadeDrive(velocity, rotation);
  }

  @Override
  public void simulationPeriodic() {}
}
